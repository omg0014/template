def fetch(pid):
    for attempt in range(5):
        try:
            return urllib.request.urlopen(f"https://images.unsplash.com/photo-{pid}?w=1600&q=85&fm=jpg", timeout=120).read()
        except Exception:
            time.sleep(2 + attempt * 3)
    raise RuntimeError(f"failed to download {pid}")


def work(pair):
    slug, pid = pair
    im = Image.open(io.BytesIO(fetch(pid))).convert("RGB")
    w0, h0 = im.size
    for w in WIDTHS:
        r = im if w >= w0 else im.resize((w, round(h0 * w / w0)), Image.LANCZOS)
        r.save(os.path.join(OUT, f"{slug}-{w}.webp"), "WEBP", quality=72, method=6)
    thumb = im.resize((20, max(1, round(h0 * 20 / w0))), Image.LANCZOS)
    buf = io.BytesIO()
    thumb.save(buf, "WEBP", quality=40)
    return slug, {"w": w0, "h": h0, "lqip": "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode(), "credit": f"https://unsplash.com/photos/{pid}"}


def main():
    os.makedirs(OUT, exist_ok=True)
    pairs = [line.split() for line in PHOTOS.strip().splitlines()]
    with cf.ThreadPoolExecutor(6) as ex:
        meta = dict(sorted(ex.map(work, pairs)))
    with open(MANIFEST, "w") as f:
        f.write("// AUTO-GENERATED by scripts/fetch-images.py — photo metadata (intrinsic size, blur placeholder, Unsplash credit).\n")
        f.write("// Files live in /public/images/<slug>-{480,960,1600}.webp\n")
        f.write("export const IMAGE_META = " + json.dumps(meta, indent=2) + "\n")
    print(f"✓ {len(meta)} images → public/images, manifest → src/data/images.js")


if __name__ == "__main__":
    sys.exit(main())
